// Command gen writes the amd64 kernels that rewrite ASCII case.
//
// A kernel walks the source in vector-sized chunks and returns how many bytes
// it wrote. A chunk with any non-ASCII byte stops the kernel, and the Go path
// finishes from there. Inside a chunk a lane changes only when it sits in
// [lo, hi]. The compare is signed and strict, so the low bound is lo-1, and a
// negative delta is a subtract so it cannot carry into the next lane. The span
// arrives as one integer: lo, hi, the magnitude of delta, and a sign byte.
//
// The packages this module builds do not import it. avo is a generator, and the
// assembly it writes is what the container package links.
package main

import (
	"bytes"
	"fmt"
	"os"

	"github.com/mmcloughlin/avo/build"
	"github.com/mmcloughlin/avo/operand"
	"github.com/mmcloughlin/avo/reg"
)

// The packed span stores hi, |delta| and the sign at SPEC_HI, SPEC_DELTA and
// SPEC_SIGN, and SPEC_BYTE selects one of those bytes. HIGH_BYTE marks a
// non-ASCII lane. LEAF_INFO and LEAF_EXT are the CPUID leaves, and the bits
// beside them are what those leaves report. XCR_YMM is the XCR0 mask the OS
// must enable before a YMM instruction is safe. SSE_STEP and AVX_STEP are the
// chunk sizes, SHUFFLE_LO broadcasts the low dword, and FILE_MODE is the mode
// of the generated assembly file.
const (
	SPEC_HI     = 8
	SPEC_DELTA  = 16
	SPEC_SIGN   = 24
	SPEC_BYTE   = 0xFF
	HIGH_BYTE   = 0x80
	LEAF_INFO   = 1
	LEAF_EXT    = 7
	OSXSAVE_BIT = 1 << 27
	AVX_BIT     = 1 << 28
	AVX2_BIT    = 1 << 5
	XCR_YMM     = 0x6
	SSE_STEP    = 16
	AVX_STEP    = 32
	SHUFFLE_LO  = 0
	FILE_MODE   = 0o644
)

// Main writes the kernels and replaces avo's banner with the marker this
// repository requires on the first line of a generated file.
//
// Revisions:
//   - 2026-10-13 17:25: initial creation
//   - 2026-10-13 21:57: stamp the banner here
func main() {
	build.Package("github.com/thebagchi/arena-go/container")
	build.ConstraintExpr("amd64")
	_EmitHas()
	_EmitRewrite()
	build.Generate()

	path := ""

	for i, arg := range os.Args {
		if arg == "-out" && i+1 < len(os.Args) {
			path = os.Args[i+1]
		}
	}

	if path == "" {
		return
	}

	body, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, fmt.Errorf("read assembly: %w", err))
		os.Exit(1)
	}

	nl := bytes.IndexByte(body, '\n')
	if nl < 0 {
		fmt.Fprintln(os.Stderr, "assembly has no line break")
		os.Exit(1)
	}

	head := []byte("// Code generated by avo. DO NOT EDIT.\n")

	err = os.WriteFile(path, append(head, body[nl+1:]...), FILE_MODE)
	if err != nil {
		fmt.Fprintln(os.Stderr, fmt.Errorf("write assembly: %w", err))
		os.Exit(1)
	}
}

// _EmitHas writes the CPUID check for AVX2.
//
// Leaf 0 leaves the highest supported leaf in RAX, and AVX2 is reported on
// leaf 7. Leaf 1 must show both OSXSAVE and AVX, and XCR0 must have XMM and
// YMM state, or a YMM instruction faults. Leaf 7 subleaf 0 then has the AVX2
// bit. Any failure returns false.
//
// Revisions:
//   - 2026-10-13 17:25: initial creation
//   - 2026-10-13 17:56: rename to the leading-_ form
//   - 2026-10-13 21:57: the leaf checks are part of this function
func _EmitHas() {
	build.TEXT("_HasAVX2", build.NOSPLIT, "func() bool")
	build.XORQ(reg.RAX, reg.RAX)
	build.CPUID()
	build.CMPQ(reg.RAX, operand.Imm(LEAF_EXT))
	build.JB(operand.LabelRef("noavx"))

	build.MOVQ(operand.U64(LEAF_INFO), reg.RAX)
	build.CPUID()
	build.ANDL(operand.Imm(OSXSAVE_BIT|AVX_BIT), reg.ECX)
	build.CMPL(reg.ECX, operand.Imm(OSXSAVE_BIT|AVX_BIT))
	build.JNE(operand.LabelRef("noavx"))

	build.XORQ(reg.RCX, reg.RCX)
	build.XGETBV()
	build.ANDL(operand.U32(XCR_YMM), reg.EAX)
	build.CMPL(reg.EAX, operand.U32(XCR_YMM))
	build.JNE(operand.LabelRef("noavx"))

	build.MOVQ(operand.U64(LEAF_EXT), reg.RAX)
	build.XORQ(reg.RCX, reg.RCX)
	build.CPUID()
	build.ANDL(operand.U32(AVX2_BIT), reg.EBX)
	build.JZ(operand.LabelRef("noavx"))

	build.MOVB(operand.Imm(1), reg.AL)
	build.Store(reg.AL, build.ReturnIndex(0))
	build.RET()

	build.Label("noavx")
	build.MOVB(operand.Imm(0), reg.AL)
	build.Store(reg.AL, build.ReturnIndex(0))
	build.RET()
}

// _EmitRewrite writes the 16-byte kernel and the 32-byte kernel.
//
// SSE2 is the amd64 baseline, so the 16-byte kernel does not consult CPUID.
// PCMPGTB is signed and strict, and it overwrites its destination, so each
// compare starts from a copy of the chunk. Lanes greater than lo-1, and not
// greater than hi, form the inclusive range. A set sign subtracts |delta|,
// because a negative add would carry into the next lane.
//
// Go writes the destination last on the 32-byte kernel. The compare encodes
// as dest = second > first, so the threshold is the first operand and the
// chunk is the second. VPANDN encodes as dest = ~second & first, and VPSUBB
// as dest = second - first. VZEROUPPER runs on the way out, including the
// chunk that stopped on a non-ASCII byte, so a later SSE instruction does not
// pay for a dirty YMM state.
//
// Revisions:
//   - 2026-10-13 21:57: initial creation
func _EmitRewrite() {
	build.TEXT("_RewriteSSE2", build.NOSPLIT, "func(dst []byte, src []byte, spec uint64) int")

	var (
		dst  = build.Load(build.Param("dst").Base(), build.GP64())
		src  = build.Load(build.Param("src").Base(), build.GP64())
		left = build.Load(build.Param("src").Len(), build.GP64())
		spec = build.Load(build.Param("spec"), build.GP64())
		done = build.GP64()
	)
	build.XORQ(done, done)

	var (
		below = build.GP32()
		full  = build.GP64()
		loVec = build.XMM()
	)
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), below)
	build.ANDL(operand.U32(SPEC_BYTE), below)
	build.SUBL(operand.U32(1), below)
	build.MOVD(below, loVec)
	build.PUNPCKLBW(loVec, loVec)
	build.PUNPCKLWL(loVec, loVec)
	build.PSHUFD(operand.Imm(SHUFFLE_LO), loVec, loVec)

	hi := build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), hi)
	build.SHRL(operand.U8(SPEC_HI), hi)
	build.ANDL(operand.U32(SPEC_BYTE), hi)

	hiVec := build.XMM()
	build.MOVD(hi, hiVec)
	build.PUNPCKLBW(hiVec, hiVec)
	build.PUNPCKLWL(hiVec, hiVec)
	build.PSHUFD(operand.Imm(SHUFFLE_LO), hiVec, hiVec)

	var (
		topByte = build.GP32()
		topVec  = build.XMM()
	)
	build.MOVL(operand.U32(HIGH_BYTE), topByte)
	build.MOVD(topByte, topVec)
	build.PUNPCKLBW(topVec, topVec)
	build.PUNPCKLWL(topVec, topVec)
	build.PSHUFD(operand.Imm(SHUFFLE_LO), topVec, topVec)

	step := build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), step)
	build.SHRL(operand.U8(SPEC_DELTA), step)
	build.ANDL(operand.U32(SPEC_BYTE), step)

	stepVec := build.XMM()
	build.MOVD(step, stepVec)
	build.PUNPCKLBW(stepVec, stepVec)
	build.PUNPCKLWL(stepVec, stepVec)
	build.PSHUFD(operand.Imm(SHUFFLE_LO), stepVec, stepVec)

	neg := build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), neg)
	build.SHRL(operand.U8(SPEC_SIGN), neg)
	build.ANDL(operand.U32(SPEC_BYTE), neg)

	build.Label("sse_loop")
	build.CMPQ(left, operand.Imm(SSE_STEP))
	build.JB(operand.LabelRef("sse_done"))

	var (
		got     = build.XMM()
		maskReg = build.XMM()
		mask    = build.GP32()
	)
	build.MOVUPS(operand.Mem{Base: src}, got)
	build.MOVAPS(got, maskReg)
	build.PAND(topVec, maskReg)
	build.PMOVMSKB(maskReg, mask)
	build.TESTL(mask, mask)
	build.JNE(operand.LabelRef("sse_done"))

	var (
		gtLo = build.XMM()
		keep = build.XMM()
		adj  = build.XMM()
	)
	build.MOVAPS(got, gtLo)
	build.PCMPGTB(loVec, gtLo)
	build.MOVAPS(got, keep)
	build.PCMPGTB(hiVec, keep)
	build.PANDN(gtLo, keep)
	build.MOVAPS(stepVec, adj)
	build.PAND(keep, adj)
	build.TESTL(neg, neg)
	build.JNE(operand.LabelRef("sse_sub"))
	build.PADDB(adj, got)
	build.JMP(operand.LabelRef("sse_store"))
	build.Label("sse_sub")
	build.PSUBB(adj, got)
	build.Label("sse_store")

	build.MOVUPS(got, operand.Mem{Base: dst})
	build.ADDQ(operand.Imm(SSE_STEP), src)
	build.ADDQ(operand.Imm(SSE_STEP), dst)
	build.ADDQ(operand.Imm(SSE_STEP), done)
	build.SUBQ(operand.Imm(SSE_STEP), left)
	build.JMP(operand.LabelRef("sse_loop"))

	build.Label("sse_done")
	build.Store(done, build.ReturnIndex(0))
	build.RET()

	build.TEXT("_RewriteAVX2", build.NOSPLIT, "func(dst []byte, src []byte, spec uint64) int")

	dst = build.Load(build.Param("dst").Base(), build.GP64())
	src = build.Load(build.Param("src").Base(), build.GP64())
	left = build.Load(build.Param("src").Len(), build.GP64())
	spec = build.Load(build.Param("spec"), build.GP64())
	done = build.GP64()
	build.XORQ(done, done)

	below = build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), below)
	build.ANDL(operand.U32(SPEC_BYTE), below)
	build.SUBL(operand.U32(1), below)

	loLow := build.XMM()
	loVec = build.YMM()

	build.MOVD(below, loLow)
	build.VPBROADCASTB(loLow, loVec)

	hi = build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), hi)
	build.SHRL(operand.U8(SPEC_HI), hi)
	build.ANDL(operand.U32(SPEC_BYTE), hi)

	hiLow := build.XMM()
	hiVec = build.YMM()

	build.MOVD(hi, hiLow)
	build.VPBROADCASTB(hiLow, hiVec)

	topByte = build.GP32()
	build.MOVL(operand.U32(HIGH_BYTE), topByte)

	topLow := build.XMM()
	topVec = build.YMM()

	build.MOVD(topByte, topLow)
	build.VPBROADCASTB(topLow, topVec)

	step = build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), step)
	build.SHRL(operand.U8(SPEC_DELTA), step)
	build.ANDL(operand.U32(SPEC_BYTE), step)

	stepLow := build.XMM()
	stepVec = build.YMM()

	build.MOVD(step, stepLow)
	build.VPBROADCASTB(stepLow, stepVec)

	neg = build.GP32()
	full = build.GP64()
	build.MOVQ(spec, full)
	build.MOVL(full.As32(), neg)
	build.SHRL(operand.U8(SPEC_SIGN), neg)
	build.ANDL(operand.U32(SPEC_BYTE), neg)

	build.Label("avx_loop")
	build.CMPQ(left, operand.Imm(AVX_STEP))
	build.JB(operand.LabelRef("avx_done"))

	got = build.YMM()
	maskY := build.YMM()
	mask = build.GP32()

	build.VMOVDQU(operand.Mem{Base: src}, got)
	build.VPAND(got, topVec, maskY)
	build.VPMOVMSKB(maskY, mask)
	build.TESTL(mask, mask)
	build.JNE(operand.LabelRef("avx_done"))

	gtLo = build.YMM()
	past := build.YMM()
	keep = build.YMM()
	adj = build.YMM()
	out := build.YMM()

	build.VPCMPGTB(loVec, got, gtLo)
	build.VPCMPGTB(hiVec, got, past)
	build.VPANDN(gtLo, past, keep)
	build.VPAND(stepVec, keep, adj)
	build.TESTL(neg, neg)
	build.JNE(operand.LabelRef("avx_sub"))
	build.VPADDB(got, adj, out)
	build.JMP(operand.LabelRef("avx_store"))
	build.Label("avx_sub")
	build.VPSUBB(adj, got, out)
	build.Label("avx_store")

	build.VMOVDQU(out, operand.Mem{Base: dst})
	build.ADDQ(operand.Imm(AVX_STEP), src)
	build.ADDQ(operand.Imm(AVX_STEP), dst)
	build.ADDQ(operand.Imm(AVX_STEP), done)
	build.SUBQ(operand.Imm(AVX_STEP), left)
	build.JMP(operand.LabelRef("avx_loop"))

	build.Label("avx_done")
	build.VZEROUPPER()
	build.Store(done, build.ReturnIndex(0))
	build.RET()
}
